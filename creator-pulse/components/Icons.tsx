type Props = { size?: number; className?: string; style?: React.CSSProperties };

function Fill({
  size = 14,
  viewBox,
  className,
  style,
  children,
}: Props & { viewBox: string; children: React.ReactNode }) {
  return (
    <svg
      width={size}
      height={size}
      viewBox={viewBox}
      fill="currentColor"
      className={className}
      aria-hidden="true"
      style={{ flex: "none", display: "block", ...style }}
    >
      {children}
    </svg>
  );
}

function Stroke({ size = 14, className, style, children }: Props & { children: React.ReactNode }) {
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={1.75}
      strokeLinecap="round"
      strokeLinejoin="round"
      className={className}
      aria-hidden="true"
      style={{ flex: "none", display: "block", ...style }}
    >
      {children}
    </svg>
  );
}

